const cache = new Map();

const fuse = new Fuse(Object.keys(Items), {
    threshold: 0.3,
    includeScore: true
});

const cleanName = (name) => {
    if (!name) return '';
    return name
        .replace(/\s+?\d+\s*[XxХх]\s*$/, '')
        .replace(/\s+?\s*[XxХх]\d+\s*$/, '')
        .replace(/\s+?\d+\s*[XxХх]\s+\s*\([^)]+\)\s*$/, "")
        .replace(/\s*\([^)]+\)\s*$/, '')
        .trim()
        .toLowerCase();
};

export const parseItem = (name) => {
    const Iname = name?.trim();
    if (!Iname) return "/data/undefined_tab.png";

    // Проверяем кэш
    if (cache.has(Iname)) {
        return cache.get(Iname);
    }

    const cleaned = cleanName(Iname);
    let result = "/data/undefined_tab.png";

    // 1. Точное совпадение
    if (Items[cleaned]) {
        result = Items[cleaned];
    }
    // 2. startsWith
    else {
        const startsWithMatch = Object.keys(Items).find(key => key.startsWith(cleaned));
        if (startsWithMatch) {
            result = Items[startsWithMatch];
        }
        // 3. Fuse
        else {
            const results = fuse.search(cleaned);
            if (results.length > 0) {
                result = Items[results[0].item];
            }
        }
    }

    // Сохраняем в кэш
    cache.set(Iname, result);
    return result;
};